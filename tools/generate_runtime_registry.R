#!/usr/bin/env Rscript

write_expression_assignment <- function(con, name, path) {
  expr <- parse(file = path, keep.source = FALSE)
  lines <- escape_non_ascii(capture.output(dput(expr)))
  writeLines(sprintf("%s <- ", name), con = con, sep = "")
  writeLines(lines, con = con)
  writeLines("", con = con)
}

escape_non_ascii <- function(lines) {
  escaped_lines <- vapply(
    enc2utf8(lines),
    function(line) {
      code_points <- utf8ToInt(line)
      escaped <- vapply(
        code_points,
        function(code_point) {
          if (code_point <= 127L) {
            intToUtf8(code_point)
          } else if (code_point <= 65535L) {
            sprintf("\\u%04X", code_point)
          } else {
            sprintf("\\U%08X", code_point)
          }
        },
        character(1),
        USE.NAMES = FALSE
      )
      paste0(escaped, collapse = "")
    },
    character(1),
    USE.NAMES = FALSE
  )
  sub("[[:space:]]+$", "", escaped_lines)
}

resolve_script_path <- function() {
  source_frame <- tryCatch(sys.frame(1L)$ofile, error = function(...) NULL)
  if (!is.null(source_frame) && nzchar(source_frame)) {
    return(normalizePath(source_frame, winslash = "/", mustWork = TRUE))
  }

  args <- commandArgs(trailingOnly = FALSE)
  file_arg <- grep("^--file=", args, value = TRUE)
  if (length(file_arg) > 0L) {
    return(normalizePath(sub("^--file=", "", file_arg[[1L]]), winslash = "/", mustWork = TRUE))
  }

  stop("Unable to resolve the path to tools/generate_runtime_registry.R.", call. = FALSE)
}

repo_root <- normalizePath(file.path(dirname(resolve_script_path()), ".."), winslash = "/", mustWork = TRUE)

runtime_root <- file.path(repo_root, "tools", "runtime_source", "ndm_runtime")
run_api_path <- file.path(runtime_root, "SetupEnv", "Analysis2_api.R")
multidisease_driver_path <- file.path(runtime_root, "SetupEnv", "Analysis2_legacy_multidisease_driver.R")
output_path <- file.path(repo_root, "R", "runtime_registry_generated.R")
temporary_output_path <- tempfile(
  pattern = ".runtime_registry_generated-",
  tmpdir = dirname(output_path),
  fileext = ".R"
)
on.exit(unlink(temporary_output_path), add = TRUE)

runtime_files <- c(
  "SetupEnv/SuperLModel_helperFxns.R",
  "SetupEnv/SuperLModel_MasterImports.R",
  "SetupData/SuperLModel_CalibrateML.R",
  "SetupData/SuperLModel_DataGenerator_Sim.R",
  "SetupData/SuperLModel_DataGenerator_Real.R",
  "SetupData/MultiDiseaseRuns/SuperL_UniversalDataReader.R",
  "ModelDefiners/SuperLModel_BuildML.R",
  "ModelDefiners/SuperLModel_BackboneTransformer.R",
  "ModelDefiners/SuperLModel_ParseDynamicODE.R",
  "ModelTrainers/SuperLModel_TrainDefine.R",
  "ModelTrainers/SuperLModel_TrainDo.R",
  "ResultsGet/SuperLModel_GetAnalytics.R",
  "ResultsGet/SuperLModel_GetAnalytics_Real.R",
  "ResultsGet/SuperLModel_GetAnalytics_Sim.R",
  "ResultsAnalyze/SuperLModel_GenFigs.R",
  "ResultsAnalyze/SuperLModel_GenFigs_RealPreprocess.R",
  "ResultsAnalyze/SuperLModel_GenFigs_GenInputStats.R",
  "ResultsAnalyze/SuperLModel_GenScalingResults.R"
)

stage_names <- gsub("[^A-Za-z0-9]+", "_", sub("\\.R$", "", runtime_files))

con <- file(temporary_output_path, open = "w", encoding = "UTF-8")
on.exit(if (isOpen(con)) close(con), add = TRUE)

writeLines("# Code generated by tools/generate_runtime_registry.R; do not edit by hand.", con = con)
writeLines("", con = con)
writeLines(".ndm_eval_runtime_stage_expr <- function(expr, env) {", con = con)
writeLines("  stopifnot(is.environment(env))", con = con)
writeLines("  eval(expr, envir = env)", con = con)
writeLines("  invisible(env)", con = con)
writeLines("}", con = con)
writeLines("", con = con)

for (i in seq_along(runtime_files)) {
  write_expression_assignment(
    con = con,
    name = sprintf(".ndm_stage_expr_%s", stage_names[[i]]),
    path = file.path(runtime_root, runtime_files[[i]])
  )
}

writeLines(".ndm_runtime_stage_registry <- local({", con = con)
writeLines("  list(", con = con)
for (i in seq_along(runtime_files)) {
  comma <- if (i < length(runtime_files)) "," else ""
  writeLines(
    sprintf(
      "    %s = function(env) .ndm_eval_runtime_stage_expr(.ndm_stage_expr_%s, env)%s",
      encodeString(runtime_files[[i]], quote = "\""),
      stage_names[[i]],
      comma
    ),
    con = con
  )
}
writeLines("  )", con = con)
writeLines("})", con = con)
writeLines("", con = con)

write_expression_assignment(con = con, name = ".ndm_run_impl_expr", path = run_api_path)
write_expression_assignment(con = con, name = ".ndm_multidisease_driver_expr", path = multidisease_driver_path)

writeLines(".ndm_new_run_impl_env <- function() {", con = con)
writeLines("  env <- new.env(parent = baseenv())", con = con)
writeLines("  eval(.ndm_run_impl_expr, envir = env)", con = con)
writeLines("  env", con = con)
writeLines("}", con = con)
writeLines("", con = con)

writeLines(".ndm_eval_multidisease_driver <- function(env) {", con = con)
writeLines("  .ndm_eval_runtime_stage_expr(.ndm_multidisease_driver_expr, env)", con = con)
writeLines("}", con = con)
close(con)

# Validate the generated assignments against the source expressions themselves,
# rather than round-tripping through this generator's serializer.
generated_env <- new.env(parent = baseenv())
sys.source(temporary_output_path, envir = generated_env, keep.source = FALSE)

for (i in seq_along(runtime_files)) {
  generated_expr <- get(
    sprintf(".ndm_stage_expr_%s", stage_names[[i]]),
    envir = generated_env,
    inherits = FALSE
  )
  source_expr <- parse(
    file = file.path(runtime_root, runtime_files[[i]]),
    keep.source = FALSE
  )
  if (!isTRUE(all.equal(generated_expr, source_expr))) {
    stop(
      "Generated runtime expression differs from source semantics: ",
      runtime_files[[i]],
      call. = FALSE
    )
  }
}

special_runtime_files <- c(
  ".ndm_run_impl_expr" = "SetupEnv/Analysis2_api.R",
  ".ndm_multidisease_driver_expr" = "SetupEnv/Analysis2_legacy_multidisease_driver.R"
)
for (expr_name in names(special_runtime_files)) {
  generated_expr <- get(expr_name, envir = generated_env, inherits = FALSE)
  source_expr <- parse(
    file = file.path(runtime_root, special_runtime_files[[expr_name]]),
    keep.source = FALSE
  )
  if (!isTRUE(all.equal(generated_expr, source_expr))) {
    stop(
      "Generated runtime expression differs from source semantics: ",
      special_runtime_files[[expr_name]],
      call. = FALSE
    )
  }
}

generated_bytes <- readBin(
  temporary_output_path,
  what = "raw",
  n = file.info(temporary_output_path)$size
)
if (any(as.integer(generated_bytes) > 0x7F)) {
  stop("Generated runtime registry must contain only ASCII bytes.", call. = FALSE)
}
if (!file.rename(temporary_output_path, output_path)) {
  stop("Could not atomically publish generated runtime registry.", call. = FALSE)
}
